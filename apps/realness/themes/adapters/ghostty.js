/** Ghostty and the browser terminal share this format. */
export const ghostty = ({ name, scheme, roles: r }) => {
  const slots = ["terminal-black", "error", "success", "warning", "working", "secondary", "syntax-cyan", "terminal-white", "terminal-bright-black", "terminal-bright-error", "terminal-bright-success", "terminal-bright-warning", "terminal-bright-working", "terminal-bright-secondary", "syntax-cyan", "terminal-bright-white"]
  return [
    `# ${name} ${scheme}. Generated by bin/graphics/themes.js; do not edit.`,
    ...slots.map((role, index) => `palette = ${index}=${r[role]}`),
    `background = ${r.background}`, `foreground = ${r.text}`,
    `cursor-color = ${r.cursor}`, `cursor-text = ${r.background}`,
    `selection-background = ${r.selection}`, `selection-foreground = ${r["selection-text"]}`,
  ].join("\n") + "\n"
}
