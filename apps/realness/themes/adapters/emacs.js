/** Emacs deftheme for one scheme; Doom loads it from its user themes directory. */
export const emacs = ({ name, scheme, roles }) => {
  const theme = `${name}-${scheme}`
  const spec = ([face, foreground, background, weight]) => {
    const attributes = [
      foreground && `:foreground "${roles[foreground]}"`,
      background && `:background "${roles[background]}"`,
      weight && `:weight ${weight}`
    ]
      .filter(Boolean)
      .join(' ')
    return `   '(${face} ((t (${attributes}))))`
  }
  return `;;; ${theme}-theme.el --- Generated by bin/graphics/themes.js; do not edit. -*- lexical-binding: t -*-
(deftheme ${theme})
(custom-theme-set-faces
 '${theme}
${faces.map(spec).join('\n')})
(provide-theme '${theme})
`
}
